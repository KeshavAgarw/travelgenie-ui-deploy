"use client";

import { Download } from "lucide-react";
import { Button } from "@/components/ui/button";
import { getTripRequest, getTripTitle } from "@/lib/trip-context";

interface TripHeaderProps {
  title?: string;
  subtitle?: string;
}

export function TripHeader({ title, subtitle }: TripHeaderProps) {
  const tripRequest = getTripRequest();
  const tripTitle = getTripTitle(tripRequest);

  const defaultSubtitle = tripRequest
    ? `Generated by TravelGenie AI · 4 agents · ${tripRequest.days} days · ${tripRequest.travelers} travelers`
    : "Generated by TravelGenie AI · 4 agents";

  return (
    <header className="flex flex-col gap-4 border-b border-slate-200 bg-white px-8 py-6 sm:flex-row sm:items-start sm:justify-between">
      <div>
        <h1 className="text-2xl font-bold tracking-tight text-slate-900">
          {title ?? tripTitle}
        </h1>
        <p className="mt-1 text-sm text-slate-500">
          {subtitle ?? defaultSubtitle}
        </p>
      </div>
      <div className="flex items-center gap-3">
        <span className="hidden text-sm text-slate-500 sm:inline">
          {tripTitle}
        </span>
        <Button variant="outline" size="sm" className="gap-2">
          <Download className="size-4" />
          Export
        </Button>
      </div>
    </header>
  );
}
